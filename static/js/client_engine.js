function clientTokenize(text) {
    if (!text) return [];
    return text.toLowerCase().replace(/[^a-z0-9 ]/g, ' ').split(/\s+/).filter(t => t.length > 1);
}

function clientBM25(query, papers) {
    const qTokens = clientTokenize(query);
    if (!qTokens.length) return {};

    const N = papers.length;
    let totalLen = 0;
    const docTokens = {};
    const docLens = {};
    const df = {};

    papers.forEach(p => {
        const tokens = clientTokenize(p.title + ' ' + p.abstract + ' ' + (p.keywords || ''));
        docTokens[p.id] = tokens;
        docLens[p.id] = tokens.length;
        totalLen += tokens.length;

        const uniqueTokens = new Set(tokens);
        uniqueTokens.forEach(t => {
            df[t] = (df[t] || 0) + 1;
        });
    });

    const avgdl = totalLen / N;
    const k1 = 1.5;
    const b = 0.75;
    const scores = {};

    papers.forEach(p => {
        const tokens = docTokens[p.id] || [];
        const tf = {};
        tokens.forEach(t => tf[t] = (tf[t] || 0) + 1);

        let score = 0;
        qTokens.forEach(q => {
            const n_q = df[q] || 0;
            if (n_q > 0) {
                const idf = Math.log(1 + (N - n_q + 0.5) / (n_q + 0.5));
                const f = tf[q] || 0;
                const denom = f + k1 * (1 - b + b * (docLens[p.id] / avgdl));
                score += idf * (f * (k1 + 1)) / denom;
            }
        });
        scores[p.id] = score;
    });

    const maxScore = Math.max(...Object.values(scores), 1e-6);
    Object.keys(scores).forEach(id => scores[id] = scores[id] / maxScore);
    return scores;
}

function clientShortestPath(sourceId, targetId) {
    sourceId = parseInt(sourceId);
    targetId = parseInt(targetId);
    if (sourceId === targetId) return [sourceId];

    const adj = {};
    BUNDLE_DATA.graph.edges.forEach(e => {
        if (!adj[e.source]) adj[e.source] = [];
        adj[e.source].push(e.target);
    });

    const queue = [[sourceId]];
    const visited = new Set([sourceId]);

    while (queue.length > 0) {
        const path = queue.shift();
        const curr = path[path.length - 1];

        const neighbors = adj[curr] || [];
        for (const n of neighbors) {
            if (n === targetId) return [...path, n];
            if (!visited.has(n)) {
                visited.add(n);
                queue.push([...path, n]);
            }
        }
    }
    return [];
}

function clientAnalyzeManuscript(text) {
    const tokens = clientTokenize(text);
    const domainKeywords = {
        'Natural Language Processing': ['transformer', 'attention', 'bert', 'nlp', 'language', 'sentiment', 'summarization', 'translation', 'sequence'],
        'Computer Vision': ['image', 'vision', 'resnet', 'cnn', 'object', 'detection', 'segmentation', 'yolo', 'convolutional', 'patches'],
        'Graph Machine Learning': ['graph', 'gcn', 'network', 'node', 'edge', 'spectral', 'convolutional', 'citation'],
        'Reinforcement Learning': ['reinforcement', 'reward', 'policy', 'agent', 'q-learning', 'markov', 'action'],
        'Machine Learning': ['learning', 'classification', 'regression', 'gradient', 'boosting', 'svm', 'model', 'dataset']
    };

    const scores = {};
    Object.keys(domainKeywords).forEach(dom => {
        scores[dom] = 0;
        domainKeywords[dom].forEach(kw => {
            tokens.forEach(t => { if (t === kw) scores[dom] += 1; });
        });
    });

    let primary = 'Machine Learning';
    let maxS = -1;
    let secondary = 'Deep Learning';
    let secondS = -1;

    Object.keys(scores).forEach(dom => {
        if (scores[dom] > maxS) {
            secondary = primary;
            secondS = maxS;
            primary = dom;
            maxS = scores[dom];
        } else if (scores[dom] > secondS) {
            secondary = dom;
            secondS = scores[dom];
        }
    });

    const totalKwMatches = Math.max(1, maxS + secondS);
    const confidence = Math.min(0.96, Math.max(0.72, maxS / totalKwMatches));

    const freq = {};
    const stopWords = new Set(['this', 'that', 'with', 'from', 'have', 'were', 'which', 'their', 'present', 'propose', 'model', 'methods']);
    tokens.forEach(t => {
        if (t.length > 3 && !stopWords.has(t)) {
            freq[t] = (freq[t] || 0) + 1;
        }
    });
    const keyphrases = Object.keys(freq).sort((a,b) => freq[b] - freq[a]).slice(0, 8);

    const foundational = [...BUNDLE_DATA.papers]
        .sort((a,b) => (b.citation_count || 0) - (a.citation_count || 0))
        .slice(0, 4);

    const contemporary = [...BUNDLE_DATA.papers]
        .sort((a,b) => (b.year || 0) - (a.year || 0))
        .slice(0, 4);

    return {
        primary_domain: { domain: primary, confidence: confidence },
        secondary_domain: { domain: secondary, confidence: Math.max(0.4, confidence - 0.25) },
        keyphrases: keyphrases,
        foundational_recommendations: foundational,
        contemporary_recommendations: contemporary
    };
}

